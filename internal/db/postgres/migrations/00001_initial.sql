CREATE FUNCTION igloo_sync_owner_head() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    old_row JSONB;
    new_row JSONB;
    old_owner TEXT;
    new_owner TEXT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        old_owner := to_jsonb(OLD) ->> TG_ARGV[1];
        IF trim(old_owner) <> '' THEN
            PERFORM igloo_sync_touch_head(TG_ARGV[0], old_owner);
        END IF;
        RETURN OLD;
    END IF;

    new_row := to_jsonb(NEW);
    new_owner := new_row ->> TG_ARGV[1];
    IF trim(new_owner) <> '' THEN
        IF TG_OP = 'UPDATE' THEN
            old_row := to_jsonb(OLD);
            IF NOT EXISTS (
                SELECT 1 FROM unnest(string_to_array(TG_ARGV[2], ',')) column_name
                WHERE old_row -> column_name IS DISTINCT FROM new_row -> column_name
            ) THEN
                RETURN NEW;
            END IF;
            old_owner := old_row ->> TG_ARGV[1];
            IF old_owner IS DISTINCT FROM new_owner THEN
                UPDATE android_sync_clock SET revision = revision + 1 WHERE id = 1;
                IF trim(old_owner) <> '' THEN
                    INSERT INTO android_sync_heads (owner_kind, owner_id, revision)
                    SELECT TG_ARGV[0], old_owner, revision FROM android_sync_clock WHERE id = 1
                    ON CONFLICT (owner_kind, owner_id) DO UPDATE SET revision = EXCLUDED.revision;
                END IF;
            END IF;
        END IF;
        PERFORM igloo_sync_touch_head(TG_ARGV[0], new_owner);
    END IF;
    RETURN NEW;
END;
$$;
