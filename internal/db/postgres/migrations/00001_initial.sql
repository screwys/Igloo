CREATE FUNCTION igloo_sync_feed_old_edges() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    old_row JSONB := to_jsonb(OLD);
    new_row JSONB;
    column_name TEXT;
    owner TEXT;
BEGIN
    IF TG_OP = 'UPDATE' THEN new_row := to_jsonb(NEW); END IF;
    FOREACH column_name IN ARRAY ARRAY['quote_tweet_id', 'reply_to_status'] LOOP
        owner := old_row ->> column_name;
        IF coalesce(owner, '') <> ''
           AND (TG_OP = 'DELETE' OR old_row -> column_name IS DISTINCT FROM new_row -> column_name) THEN
            PERFORM 1 FROM android_sync_clock WHERE id = 1 FOR UPDATE;
            IF EXISTS (SELECT 1 FROM feed_items WHERE tweet_id = owner) THEN
                PERFORM igloo_sync_touch_head('feed', owner);
            END IF;
        END IF;
    END LOOP;
    RETURN NULL;
END;
$$;
