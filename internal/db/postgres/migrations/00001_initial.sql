CREATE FUNCTION igloo_search_document(VARIADIC fields TEXT[]) RETURNS TSVECTOR
LANGUAGE plpgsql STABLE PARALLEL SAFE AS $$
DECLARE
    value TEXT;
    document TSVECTOR := ''::TSVECTOR;
BEGIN
    FOREACH value IN ARRAY fields LOOP
        -- A position gap keeps phrases within one field.
        document := document || (quote_literal(chr(31)) || ':1')::TSVECTOR ||
            to_tsvector('simple', regexp_replace(lower(unaccent(coalesce(value, '')) COLLATE "pg_c_utf8"), '[^[:alnum:]]+', ' ', 'g'));
    END LOOP;
    RETURN ts_delete(document, chr(31));
END;
$$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE FUNCTION igloo_search_query(value TEXT) RETURNS TSQUERY
LANGUAGE plpgsql STABLE PARALLEL SAFE AS $$
DECLARE
    term TEXT;
    tokens TEXT[];
    position INTEGER;
    query_text TEXT := '';
    term_query TEXT;
BEGIN
    FOREACH term IN ARRAY regexp_split_to_array(trim(value), '\s+') LOOP
        tokens := regexp_split_to_array(trim(regexp_replace(lower(unaccent(term) COLLATE "pg_c_utf8"), '[^[:alnum:]]+', ' ', 'g')), '\s+');
        term_query := '';
        FOR position IN 1..cardinality(tokens) LOOP
            IF tokens[position] <> '' THEN
                IF term_query <> '' THEN term_query := term_query || ' <-> '; END IF;
                term_query := term_query || quote_literal(tokens[position]);
                IF position = cardinality(tokens) THEN term_query := term_query || ':*'; END IF;
            END IF;
        END LOOP;
        IF term_query <> '' THEN
            IF query_text <> '' THEN query_text := query_text || ' & '; END IF;
            query_text := query_text || '(' || term_query || ')';
        END IF;
    END LOOP;
    RETURN query_text::TSQUERY;
END;
$$;
