CREATE FUNCTION igloo_sync_setting_heads() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    relevant TEXT[] := ARRAY['moments_include_reposts_default', 'instagram_include_tagged_default',
        'include_reposts_default', 'translate_target_lang', 'translate_skip_langs',
        'x_account_region_enabled', 'x_community_notes_enabled'];
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.key = ANY(relevant) THEN PERFORM igloo_sync_touch_head('setting', OLD.key); END IF;
        RETURN OLD;
    ELSIF TG_OP = 'UPDATE' THEN
        IF OLD.key IS NOT DISTINCT FROM NEW.key AND OLD.value IS NOT DISTINCT FROM NEW.value THEN
            RETURN NEW;
        END IF;
        IF OLD.key IS DISTINCT FROM NEW.key AND OLD.key = ANY(relevant) THEN
            PERFORM igloo_sync_touch_head('setting', OLD.key);
        END IF;
    END IF;
    IF NEW.key = ANY(relevant) THEN PERFORM igloo_sync_touch_head('setting', NEW.key); END IF;
    RETURN NEW;
END;
$$;
