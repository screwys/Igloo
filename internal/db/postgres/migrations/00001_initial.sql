CREATE FUNCTION igloo_sync_feed_peers() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    old_row JSONB;
    new_row JSONB;
    old_hash TEXT;
    new_hash TEXT;
    old_target TEXT;
    new_target TEXT;
    touch_old BOOLEAN;
    touch_new BOOLEAN;
BEGIN
    IF TG_OP <> 'INSERT' THEN old_row := to_jsonb(OLD); END IF;
    IF TG_OP <> 'DELETE' THEN new_row := to_jsonb(NEW); END IF;
    old_target := old_row ->> TG_ARGV[0];
    new_target := new_row ->> TG_ARGV[0];
    touch_old := (TG_OP = 'DELETE' OR (TG_OP = 'UPDATE' AND old_target IS DISTINCT FROM new_target))
        AND coalesce(old_target, '') <> '';
    touch_new := (TG_OP = 'INSERT' OR (TG_OP = 'UPDATE' AND EXISTS (
        SELECT 1 FROM unnest(string_to_array(TG_ARGV[2], ',')) column_name
        WHERE old_row -> column_name IS DISTINCT FROM new_row -> column_name
    ))) AND coalesce(new_target, '') <> '';
    IF NOT touch_old AND NOT touch_new THEN RETURN NULL; END IF;
    PERFORM 1 FROM android_sync_clock WHERE id = 1 FOR UPDATE;
    IF TG_ARGV[1] = 'lookup' THEN
        SELECT content_hash INTO old_hash FROM feed_items WHERE tweet_id = old_target;
        SELECT content_hash INTO new_hash FROM feed_items WHERE tweet_id = new_target;
    ELSE
        old_hash := old_target;
        new_hash := new_target;
    END IF;
    IF touch_old AND coalesce(old_hash, '') <> '' THEN
        PERFORM igloo_sync_touch_feed_peers(old_hash);
    END IF;
    IF touch_new AND coalesce(new_hash, '') <> '' THEN
        PERFORM igloo_sync_touch_feed_peers(new_hash);
    END IF;
    RETURN NULL;
END;
$$;
-- +goose StatementEnd

